export function getEmoji(keyword = '') {
  for (const [keywords, emoji] of KEYWORD_MAP) {
    if (keywords.some(k => keyword.includes(k))) return emoji;
  }
  const fallback = ['📖', '🌸', '⭐', '🦋', '🌈', '🎭', '🎪', '🧩', '🌟', '💫'];
  return fallback[(keyword.charCodeAt(0) || 0) % fallback.length];
}
